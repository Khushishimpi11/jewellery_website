// Helper functions
export const getProductById = (id) => {
  return productsData.find(product => product.id === parseInt(id));
};

export const getProductsByCategory = (category) => {
  if (category === 'all') return productsData;
  return productsData.filter(product => product.category === category);
};

export const getFeaturedProducts = () => {
  return productsData.slice(0, 8);
};

export const getProductsForSection = (sectionName, limit = 6) => {
  switch(sectionName) {
    case 'productGallery':
      return productsData.slice(0, 6); // First 6 products
    case 'jewelryCollection':
      return productsData.slice(6, 14); // Next 8 products
    case 'productSlider':
      return productsData.slice(14, 18); // Last 4 products
    default:
      return productsData.slice(0, limit);
  }
};